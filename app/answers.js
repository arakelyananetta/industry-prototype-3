export function matchSection(text) {
  const q = text.toLowerCase()
  const hit = NAV_STEMS.find(([, ...stems]) => stems.some((s) => q.includes(s)))
  if (!hit) return null
  const hasVerb = NAV_VERBS.some((v) => q.includes(v))
  const isShort = q.trim().split(/\s+/).length <= 2
  return hasVerb || isShort ? { id: hit[0], label: NAV_LABELS[hit[0]] } : null
}

